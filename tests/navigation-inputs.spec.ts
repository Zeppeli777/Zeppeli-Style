import { expect, test } from '@playwright/test'

test('calendar selects leap day with the keyboard and respects month bounds', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/#catalog')
  await page.getByRole('searchbox').fill('ZpCalendar')
  const view = page.locator('.catalog-preview')
  await expect(view.getByRole('button', { name: '上个月' })).toBeDisabled()
  const day = (iso: string) => view.locator('[data-value="' + iso + '"]')
  await day('2028-02-28').focus()
  await page.keyboard.press('ArrowRight')
  await expect(day('2028-02-29')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(view.getByText('赛段日期：2028-02-29')).toBeVisible()
  await view.getByRole('button', { name: '下个月' }).click()
  await expect(view.getByRole('button', { name: '下个月' })).toBeDisabled()
  await day('2028-03-01').click()
  await expect(view.getByText('赛段日期：2028-03-01')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})

test('multiple selection persists across popup opens and exposes disabled options', async ({ page }) => {
  await page.goto('/#catalog')
  await page.getByRole('searchbox').fill('ZpMultiSelect')
  const trigger = page.locator('.catalog-preview').getByRole('combobox')
  await trigger.press('Enter')
  const list = page.getByRole('listbox', { name: '记录标签' })
  await expect(list).toHaveAttribute('aria-multiselectable', 'true')
  await expect(list.getByRole('option', { name: '已封存' })).toBeDisabled()
  await list.getByRole('option', { name: '补给' }).click()
  await list.getByRole('option', { name: '天气' }).click()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveText(/路线、补给、天气/)
  await trigger.click()
  await list.getByRole('option', { name: '路线' }).click()
  await page.keyboard.press('Escape')
  await expect(trigger).toHaveText(/补给、天气/)
  await expect(trigger).not.toHaveText(/路线/)
})

test('checkboxes and sidebar work with the keyboard', async ({ page }) => {
  await page.goto('/#catalog')
  const search = page.getByRole('searchbox')
  await search.fill('ZpCheckboxGroup')
  const view = page.locator('.catalog-preview')
  await expect(view.getByLabel('路线')).toBeChecked()
  await view.getByLabel('补给站').press('Space')
  await expect(view.getByText('已启用 2 个图层')).toBeVisible()
  await search.fill('ZpCheckbox')
  await page.getByRole('list', { name: '组件列表' }).getByRole('button', { name: /ZpCheckbox$/ }).click()
  await view.getByLabel('置顶这篇手记').check()
  await expect(view.getByLabel('置顶这篇手记')).toBeChecked()
  await search.fill('ZpSidebar')
  await view.getByRole('button', { name: '勘测记录' }).press('Enter')
  await expect(view.getByText('浅滩水位下降，适合马队通行。')).toBeVisible()
  const toggle = view.getByRole('button', { name: /赛程章节/ })
  await toggle.click()
  await expect(view.getByRole('list')).toBeHidden()
  await toggle.press('Enter')
  await expect(view.getByRole('button', { name: '勘测记录' })).toHaveAttribute('aria-current', 'true')
})

test('open mobile navigation switches back to the active desktop link', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 720 })
  await page.goto('/#catalog')
  const nav = page.getByRole('navigation', { name: '主导航' })
  await nav.getByRole('button', { name: '菜单' }).click()
  await expect(page.getByRole('dialog').getByRole('link', { name: '组件目录' })).toHaveAttribute('aria-current', 'page')
  await page.setViewportSize({ width: 1000, height: 720 })
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(nav.getByRole('link', { name: '组件目录' })).toBeFocused()
  await nav.getByRole('link', { name: '设计手记' }).click()
  await expect(nav.getByRole('link', { name: '设计手记' })).toHaveAttribute('aria-current', 'page')
})
