import { expect, test } from '@playwright/test'

test('mobile navigation, Escape and article focus', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 780 })
  await page.goto('/')
  const menu = page.getByRole('button', { name: '菜单' })
  await menu.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await menu.click()
  await page.getByRole('dialog').getByRole('link', { name: '设计手记' }).click()
  await expect(page.getByRole('heading', { name: '球面上的六道刻线' })).toBeVisible()
  await page.getByRole('button', { name: '文章目录' }).click()
  await page.getByRole('button', { name: '缩到二十四像素' }).click()
  await expect(page.locator('#scale')).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})

test('desktop progress and chart controls', async ({ page }) => {
  await page.goto('/')
  const ball = page.getByAltText('带六边形凹槽的铜绿铁球')
  await expect(ball).toBeVisible()
  await expect.poll(() => ball.evaluate(img => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.getByRole('link', { name: '打开组件试验台' }).click()
  const slider = page.getByRole('slider')
  await slider.focus()
  await slider.press('End')
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '100')
  await slider.press('Home')
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '0')
  await page.getByRole('button', { name: '切换为折线图' }).click()
  await expect(page.locator('figure circle')).toHaveCount(4)
  await expect(page.locator('figure li')).toHaveCount(4)
})
